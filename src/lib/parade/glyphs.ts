// Letters and numbers as skeleton strokes in a 0.8 x 1.2 box centred on the origin.
// They are thickened into chunky tubes by glyph-geometry.ts, so no font file is needed.
export type Pt = [number, number];
export type Stroke = Pt[];

/** Points along an elliptical arc; angles in degrees, counter-clockwise from +x. */
const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 14): Stroke =>
  Array.from({ length: n + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)] as Pt;
  });
const join = (...parts: Stroke[]): Stroke => parts.flat();
const mirror = (strokes: Stroke[]): Stroke[] => strokes.map((s) => s.map(([x, y]) => [-x, -y] as Pt));

